using Bookshop.Domain.Orders;
using Microsoft.Extensions.DependencyInjection;
using Mocha.Mediator;

namespace Bookshop.Application.Common;

/// <summary>
/// Wires the Bookshop application layer's Mocha mediator into dependency injection.
/// </summary>
public static class ApplicationServiceCollectionExtensions
{
    /// <summary>
    /// Registers the Mocha mediator and every command handler declared in this assembly (the
    /// write side: <c>AddBook</c>/<c>RestockBook</c>/<c>AddAuthor</c>/<c>RegisterCustomer</c>/
    /// <c>PlaceOrder</c>/<c>CancelOrder</c>), the catalog query handlers, the order domain
    /// service, and the domain-event dispatcher used by Infrastructure's unit of work. Handler
    /// registration itself is source-generated by
    /// Mocha.Analyzers into an <c>AddApplication()</c> extension on
    /// <see cref="IMediatorHostBuilder"/> (the name is derived from the last segment of the
    /// assembly name, "Bookshop.Application" -&gt; "Application", the same convention
    /// Operations.Host uses to generate <c>AddHost()</c>); no manual handler registration is
    /// required.
    ///
    /// Query handlers depend only on DataLoader interfaces in this assembly. Their
    /// source-generated implementations remain in Infrastructure beside <c>BookshopContext</c>.
    /// </summary>
    public static IServiceCollection AddBookshopApplication(this IServiceCollection services)
    {
        services.AddSingleton<IDomainEventDispatcher, DomainEventDispatcher>();
        services.AddSingleton<OrderService>();
        services.AddMediator().AddApplication();

        return services;
    }
}
